'use strict';
// Narrow, explicit bridge between the sandboxed UI and the main process.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('native', {
  platform: process.platform,
  openProject: () => ipcRenderer.invoke('project:open'),
  saveProject: (text, filePath, name) => ipcRenderer.invoke('project:save', text, filePath, name),
  importDialog: () => ipcRenderer.invoke('media:import'),
  stat: (paths) => ipcRenderer.invoke('file:stat', paths),
  readFile: (p) => ipcRenderer.invoke('file:read', p),
  reveal: (p) => ipcRenderer.invoke('shell:reveal', p),
  exportBegin: (name, ext) => ipcRenderer.invoke('export:begin', name, ext),
  exportDefaultDir: () => ipcRenderer.invoke('export:defaultDir'),
  pickFolder: (start) => ipcRenderer.invoke('dialog:pickFolder', start),
  exportBeginPath: (dir, fileName) => ipcRenderer.invoke('export:beginPath', dir, fileName),
  fileExists: (dir, fileName) => ipcRenderer.invoke('file:exists', dir, fileName),
  fileSize: (p) => ipcRenderer.invoke('file:size', p),
  readRange: (p, start, end) => ipcRenderer.invoke('file:readRange', p, start, end),
  closeReads: () => ipcRenderer.invoke('file:closeReads'),
  exportWriteAt: (handle, data, position) => ipcRenderer.invoke('export:writeAt', handle, data, position),
  appDir: (kind) => ipcRenderer.invoke('app:dir', kind),
  writeNew: (dir, name, data) => ipcRenderer.invoke('file:writeNew', dir, name, data),
  writeFile: (p, data) => ipcRenderer.invoke('file:write', p, data),
  openFileDialog: (title, exts) => ipcRenderer.invoke('dialog:openFile', title, exts),
  saveFileDialog: (title, name, exts) => ipcRenderer.invoke('dialog:saveFile', title, name, exts),
  askMic: () => ipcRenderer.invoke('media:askMic'),
  whisperStatus: () => ipcRenderer.invoke('whisper:status'),
  whisperDownload: (id) => ipcRenderer.invoke('whisper:download', id),
  whisperTranscribe: (opts) => ipcRenderer.invoke('whisper:transcribe', opts),
  whisperCancel: () => ipcRenderer.invoke('whisper:cancel'),
  onWhisperProgress: (cb) => ipcRenderer.on('whisper-progress', (_e, p) => cb(p)),
  exportChunk: (handle, data) => ipcRenderer.invoke('export:chunk', handle, data),
  exportEnd: (handle, keep) => ipcRenderer.invoke('export:end', handle, keep),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file) || null; } catch { return null; } },
  onMenu: (cb) => ipcRenderer.on('menu', (_e, cmd) => cb(cmd)),
  closeOk: () => ipcRenderer.send('close-ok'),
  editNative: (action) => ipcRenderer.send('edit:native', action),
  setTitle: (t) => ipcRenderer.send('set-title', t),
  setEdited: (v) => ipcRenderer.send('set-edited', v),
});
